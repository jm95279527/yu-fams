#!/bin/bash
M="mysql -uroot -pYOUR_DB_PASSWORD xm-assets -N"
echo "=== MySQL 版本 ==="
$M -e "select version()"
echo "=== 菜单树（系统管理/基础资料相关）==="
$M -e "select concat(id,' | pid=',ifnull(pid,'NULL'),' | ',name,' | ',ifnull(path,''),' | api=',ifnull(api,'')) from sys_menu where name like '%基础%' or name like '%资产%' or name like '%系统%' order by id"
echo "=== 全部菜单（id/pid/name/path）==="
$M -e "select concat(id,' | ',ifnull(pid,0),' | ',name,' | ',ifnull(path,'')) from sys_menu order by id"
echo "=== assets 表结构 ==="
$M -e "desc assets"
echo "=== 现有角色 ==="
$M -e "select concat(id,' | ',name,' | ',role_key) from sys_role"
echo "=== 各角色是否拥有基础资料菜单 ==="
$M -e "select concat(rm.role_id,' | role=',r.name,' | menu=',m.name) from sys_role_menu rm join sys_role r on rm.role_id=r.id join sys_menu m on rm.menu_id=m.id where m.name like '%基础%' or m.name in ('公司信息','部门信息','资产分类') order by rm.role_id"
